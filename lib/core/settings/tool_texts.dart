/// 工具页文案查表：以简体中文为源文案，按当前语言替换。
///
/// - `tr('工资与基数')`：静态文案
/// - `trf('共 {n} 个工具', {'n': 3})`：带占位符的模板
///
/// 未收录的文案原样返回中文，新增语言只需在 [_table] 里补一层。
String tr(String zh) => _table[_langCode]?[zh] ?? zh;

String trf(String zh, Map<String, Object?> args) {
  var text = tr(zh);
  args.forEach((key, value) {
    text = text.replaceAll('{$key}', '${value ?? ''}');
  });
  return text;
}

